    {
        $response = $this->call(
            self::METHOD_POST,
            '/repos/' . \rawurlencode($owner),
            ['Authorization' => "Bearer {$this->accessToken}"],
            ['name' => $repositoryName]
        );

        $statusCode = $response['headers']['status-code'] ?? 0;
        if ($statusCode >= 400) {
            throw new Exception("Creating repository {$repositoryName} failed with status code {$statusCode}", (int) $statusCode);
        }

        return \is_array($response['body'] ?? null) ? $response['body'] : [];
    }

    /**
     * Delete repository
     *
     * The documented partner API has no deletion endpoint; this rides the
     * Cursor web app's own API instead, which names the owner `org`.
     */
    public function deleteRepository(string $owner, string $repositoryName): bool
    {
        $endpoint = $this->endpoint;
        $this->endpoint = $this->webApiEndpoint;

        try {
            $response = $this->call(
                self::METHOD_POST,
                '/delete-repo',
                [
                    'Authorization' => "Bearer {$this->accessToken}",
                    // The web API refuses cross-origin state changes outright
                    'origin' => 'https://cursor.com',
                ],
                ['identifier' => ['org' => $owner, 'name' => $repositoryName]]
            );
        } finally {
            $this->endpoint = $endpoint;
        }

        $statusCode = $response['headers']['status-code'] ?? 0;
        if ($statusCode >= 400) {
            throw new Exception("Deleting repository {$repositoryName} failed with status code {$statusCode}", (int) $statusCode);
        }

        return true;
    }

    /**
     * Get latest opened pull request with specific base branch
     *
     * @return array<mixed>
     */
    public function getPullRequestFromBranch(string $owner, string $repositoryName, string $branch): array
    {
        $response = $this->call(
            self::METHOD_GET,
            $this->repositoryPath($owner, $repositoryName) . '/pulls',
            ['Authorization' => "Bearer {$this->accessToken}"],
            ['head' => $branch, 'state' => 'open', 'pageSize' => 1]
        );

        $statusCode = $response['headers']['status-code'] ?? 0;
        if ($statusCode >= 400) {
            throw new Exception("Failed to list pull requests: HTTP {$statusCode}", (int) $statusCode);
        }

        $responseBody = \is_array($response['body'] ?? null) ? $response['body'] : [];
        $pullRequests = \is_array($responseBody['pullRequests'] ?? null) ? $responseBody['pullRequests'] : [];

        $pullRequest = $pullRequests[0] ?? [];

        return \is_array($pullRequest) && !empty($pullRequest) ? $this->normalizePullRequest($pullRequest) : [];
    }

